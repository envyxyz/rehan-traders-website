// Snapshots /dev/kitchen-sink into design/palette.html: one self-contained, offline file
// (compiled CSS and Latin fonts inlined, scripts stripped) with a light / dark / auto switch.
// Run with the dev server up:  pnpm dev  then  pnpm palette
import { writeFile } from "node:fs/promises"

const base = process.env.PALETTE_URL ?? "http://localhost:3000"
const get = async (path, as = "text") => {
  const res = await fetch(new URL(path, base))
  if (!res.ok) throw new Error(`${res.status} ${path}. Is \`pnpm dev\` running?`)
  return as === "text" ? res.text() : Buffer.from(await res.arrayBuffer())
}

const html = await get("/dev/kitchen-sink")
const sheets = [...html.matchAll(/<link rel="stylesheet" href="([^"]+)"/g)].map((m) => m[1])
let css = ""
for (const href of sheets) {
  let sheet = await get(href)
  // Keep only Latin font faces (the site loads the latin subset) and inline them.
  const faces = sheet.match(/@font-face\s*{[^}]*}/g) ?? []
  for (const face of faces) {
    const url = face.match(/url\("?([^")]+)"?\)/)?.[1]
    if (!url || !face.includes("U+??")) { sheet = sheet.replace(face, ""); continue }
    const font = await get(new URL(url, new URL(href, base)).pathname, "buffer")
    sheet = sheet.replace(face, face.replace(/url\([^)]+\)/, `url(data:font/woff2;base64,${font.toString("base64")})`))
  }
  css += sheet
}

// Turn the device-only dark block into one the switch can force.
const dark = css.match(/@media \(prefers-color-scheme: dark\) \{\s*:root \{([^}]*)\}\s*\}/)
if (!dark) throw new Error("Dark :root block not found in compiled CSS")
css = css.replace(
  dark[0],
  `:root[data-theme="light"] { color-scheme: light; }
:root[data-theme="dark"] { color-scheme: dark; ${dark[1]} }
@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) { ${dark[1]} } }`
)

const body = html
  .match(/<body[^>]*>([\s\S]*)<\/body>/)[1]
  .replace(/<script[\s\S]*?<\/script>/g, "")
  .replace(/ style="opacity:0;transform:translateY\(8px\)"/g, "") // reveals: show settled
  .replace(/<div[^>]*cmdk-empty[^>]*>[\s\S]*?<\/div>/g, "") // cmdk renders "No results" until hydrated
const htmlClass = html.match(/<html[^>]*class="([^"]*)"/)?.[1] ?? ""

const page = `<!doctype html>
<html lang="en" class="${htmlClass}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<meta name="robots" content="noindex">
<title>Rehan Traders palette</title>
<!-- Generated by scripts/palette.mjs from /dev/kitchen-sink on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand. -->
<style>${css}
.theme-switch { position: fixed; z-index: 60; top: 1rem; right: 1rem; display: inline-flex; gap: .25rem; padding: .3125rem; border-radius: 9999px; }
.theme-switch button { height: 2.25rem; padding: 0 .875rem; border: 0; border-radius: 9999px; background: none; color: var(--ink); font: 600 .875rem/1 var(--font-google-sans), Arial, sans-serif; cursor: pointer; }
.theme-switch button[aria-pressed="true"] { background: var(--action); color: var(--on-action); }
</style>
<script>
  try { const t = localStorage.getItem("palette-theme"); if (t) document.documentElement.dataset.theme = t } catch {}
</script>
</head>
<body>
<div class="theme-switch glass" role="group" aria-label="Theme">
  <button type="button" data-set="">Auto</button>
  <button type="button" data-set="light">Light</button>
  <button type="button" data-set="dark">Dark</button>
</div>
${body}
<script>
  const root = document.documentElement, buttons = document.querySelectorAll(".theme-switch button")
  const sync = () => buttons.forEach((b) => b.setAttribute("aria-pressed", String((root.dataset.theme ?? "") === b.dataset.set)))
  buttons.forEach((b) => b.addEventListener("click", () => {
    if (b.dataset.set) root.dataset.theme = b.dataset.set; else delete root.dataset.theme
    try { localStorage.setItem("palette-theme", b.dataset.set) } catch {}
    sync()
  }))
  sync()
</script>
</body>
</html>
`
await writeFile(new URL("../design/palette.html", import.meta.url), page)
console.log(`design/palette.html written (${Math.round(page.length / 1024)} KB)`)
